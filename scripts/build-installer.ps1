<#
Builds the qBittorrent ARM64 NSIS installer using upstream's own installer scripts
(qBittorrent\dist\windows\qbittorrent.nsi, which supports QBT_CPU_ARCH=arm64).

Stages <Root>\installer\ with the upstream scripts + NSIS plugins and a copy of the
built dist folder WITHOUT the portable-mode 'profile' folder, then runs makensis.

  .\scripts\build-installer.ps1 [-Root C:\dev\qbt-arm64] [-NoPdb]
#>
param(
    [string]$Root = 'C:\dev\qbt-arm64',
    [switch]$NoPdb
)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$src = Join-Path $Root 'qBittorrent\dist\windows'
$dist = Join-Path $Root 'dist\qBittorrent'
$stage = Join-Path $Root 'installer'
$makensis = @("${env:ProgramFiles(x86)}\NSIS\makensis.exe", "$env:ProgramFiles\NSIS\makensis.exe") |
    Where-Object { Test-Path $_ } | Select-Object -First 1

if (-not $makensis) { throw 'makensis.exe not found. Install NSIS: winget install NSIS.NSIS' }
if (-not (Test-Path (Join-Path $src 'qbittorrent.nsi'))) { throw "Upstream installer scripts not found in $src" }
if (-not (Test-Path (Join-Path $dist 'qbittorrent.exe'))) { throw "Build output not found in $dist. Run build-qbt.ps1 first." }

# Version from the source tree (config.nsh needs plain dotted numbers only)
$verH = Get-Content (Join-Path $Root 'qBittorrent\src\base\version.h.in') -Raw
$ver = '{0}.{1}.{2}' -f ([regex]::Match($verH, 'QBT_VERSION_MAJOR (\d+)').Groups[1].Value),
                        ([regex]::Match($verH, 'QBT_VERSION_MINOR (\d+)').Groups[1].Value),
                        ([regex]::Match($verH, 'QBT_VERSION_BUGFIX (\d+)').Groups[1].Value)
if ($ver -notmatch '^\d+\.\d+\.\d+$') { throw "Could not read version from version.h.in (got '$ver')" }

Write-Host "==> Staging installer for qBittorrent $ver arm64 in $stage"
if (Test-Path $stage) { Remove-Item $stage -Recurse -Force }
New-Item -ItemType Directory -Force $stage | Out-Null
Copy-Item (Join-Path $src '*') $stage -Recurse -Force
Expand-Archive (Join-Path $src 'NSISPlugins.zip') $stage -Force

# Payload: everything except the portable-mode profile folder (it would make the installed copy portable)
# and qt.conf (the .nsi installs its own copy)
$payload = Join-Path $stage 'qBittorrent'
New-Item -ItemType Directory -Force $payload | Out-Null
Get-ChildItem $dist | Where-Object { $_.Name -notin @('profile', 'qt.conf') -and -not ($NoPdb -and $_.Extension -eq '.pdb') } |
    Copy-Item -Destination $payload -Recurse -Force
if (Test-Path (Join-Path $payload 'profile')) { throw 'profile folder leaked into the installer payload' }

# Upstream's uninstaller only deletes the files of upstream's statically linked build (exe, pdb, qt.conf,
# translations). This build ships Qt/OpenSSL/libtorrent DLLs and Qt plugins, so generate an explicit
# delete list from the payload (no recursive wipe of $INSTDIR, in case users put their own files there).
$payloadFiles = Get-ChildItem $payload -Recurse -File | ForEach-Object { $_.FullName.Substring($payload.Length + 1) }
$payloadDirs = Get-ChildItem $payload -Recurse -Directory | ForEach-Object { $_.FullName.Substring($payload.Length + 1) } |
    Sort-Object { ($_ -split '\\').Count } -Descending
$lines = @('; Generated by build-installer.ps1 from the installer payload')
$lines += $payloadFiles | ForEach-Object { "  Delete `"`$INSTDIR\$_`"" }
$lines += $payloadDirs | ForEach-Object { "  RMDir `"`$INSTDIR\$_`"" }
Set-Content (Join-Path $stage 'uninstall-payload.nsh') $lines -Encoding utf8

$unPath = Join-Path $stage 'uninstaller.nsh'
$un = Get-Content $unPath -Raw
$anchor = [regex]::Match($un, '(?m)^(\s*)RMDir "\$INSTDIR"\s*$')
if (-not $anchor.Success) { throw 'Could not find RMDir "$INSTDIR" in uninstaller.nsh to insert the payload delete list.' }
$un = $un.Insert($anchor.Index, "$($anchor.Groups[1].Value)!include `"uninstall-payload.nsh`"`r`n")

# The NSIS stub is 32-bit, so without SetRegView 64 every HKLM\Software write lands in WOW6432Node, while the
# shared RegisteredApplications value points at Software\qBittorrent\Capabilities in the 64-bit view (so
# qBittorrent never shows up in Settings > Default apps). Use the native 64-bit view in both directions, and
# have the uninstaller remove the RegisteredApplications value, which upstream leaves behind.
function Add-AfterLine([string]$Text, [string]$Pattern, [string]$Insert, [string]$What) {
    $m = [regex]::Match($Text, $Pattern)
    if (-not $m.Success) { throw "Could not find $What to patch." }
    $Text.Insert($m.Index + $m.Length, $Insert)
}
$un = Add-AfterLine $un '(?m)^Function un\.onInit\s*\r?\n' "  SetRegView 64`r`n" 'un.onInit in uninstaller.nsh'
$un = Add-AfterLine $un '(?m)^\s*DeleteRegKey HKLM "Software\\qBittorrent"\s*\r?\n' "  DeleteRegValue HKLM `"Software\RegisteredApplications`" `"qBittorrent`"`r`n" 'DeleteRegKey HKLM Software\qBittorrent in uninstaller.nsh'
Set-Content $unPath $un -NoNewline -Encoding utf8

$inPath = Join-Path $stage 'installer.nsh'
$in = Add-AfterLine (Get-Content $inPath -Raw) '(?m)^Function \.onInit\s*\r?\n' "  SetRegView 64`r`n" '.onInit in installer.nsh'
Set-Content $inPath $in -NoNewline -Encoding utf8
Write-Host "   Uninstaller will remove $($payloadFiles.Count) payload files and $($payloadDirs.Count) folders."

Write-Host '==> Running makensis'
Push-Location $stage
try {
    & $makensis /V2 /DQBT_CPU_ARCH=arm64 "/DQBT_VERSION=$ver" qbittorrent.nsi
    if ($LASTEXITCODE -ne 0) { throw "makensis failed (exit $LASTEXITCODE)" }
}
finally { Pop-Location }

$out = Get-ChildItem $stage -Filter "qbittorrent_${ver}_arm64_setup.exe" | Select-Object -First 1
if (-not $out) { throw 'Installer exe not produced.' }
Write-Host ('==> Done: {0} ({1:N1} MB)' -f $out.FullName, ($out.Length / 1MB))
